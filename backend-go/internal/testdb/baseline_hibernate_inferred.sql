-- Baseline of the Spring Boot schema, for LOCAL TESTS ONLY. Inferred from the
-- entities and then aligned with the real Neon database (columns, identity
-- columns, unique/regular indexes) inspected read-only on 2026-11-08.
--
-- Derived from the JPA entities (src/main/java/com/game/model/*.java) and
-- Hibernate 6 defaults with spring.jpa.hibernate.ddl-auto=update: snake_case
-- names, varchar(255) for unannotated String, NOT NULL for primitives,
-- IDENTITY ids. It is NOT the real Neon schema (never inspected — plan 8.1) and
-- must never be applied to a real database. reset_game_data is intentionally
-- absent: its definition is unknown.

CREATE TABLE game_session (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at             timestamp(6),
    creator_name           varchar(255),
    current_game           varchar(255),
    current_question_index integer DEFAULT 0 NOT NULL,
    current_round_id       varchar(255),
    game_started           boolean NOT NULL,
    round_status           varchar(255),
    session_code           varchar(255)
);

CREATE TABLE users (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ready           boolean NOT NULL,
    session_token   varchar(255) UNIQUE,
    username        varchar(255) NOT NULL UNIQUE,
    game_session_id bigint REFERENCES game_session (id)
);

CREATE TABLE question (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anonymous       boolean NOT NULL,
    from_user       varchar(255),
    question        varchar(255),
    round_id        varchar(255),
    to_user         varchar(255),
    game_session_id bigint REFERENCES game_session (id)
);

CREATE TABLE shown_questions (
    session_id  bigint NOT NULL REFERENCES game_session (id),
    question_id bigint,
    seq         bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL -- present in the real DB, not in the entity
);

-- Objects observed in the real database (bd_bbtronic, read-only inspection
-- 2026-11-08) that are not derivable from the Java entities.
CREATE UNIQUE INDEX ux_game_session_code ON game_session (session_code);
CREATE INDEX idx_users_game_session ON users (game_session_id);
CREATE INDEX idx_question_session_round ON question (game_session_id, round_id);
CREATE INDEX idx_shown_questions_session ON shown_questions (session_id);
CREATE TABLE auth_sessions (
    id           text PRIMARY KEY,
    secret_hash  text NOT NULL,
    user_id      bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    session_code varchar(255),
    created_at   timestamptz NOT NULL DEFAULT now(),
    expires_at   timestamptz NOT NULL
);

CREATE TABLE yo_nunca_nunca (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto varchar(500) NOT NULL,
    tipo  varchar(255) NOT NULL
);
CREATE TABLE cultura_pendeja (LIKE yo_nunca_nunca INCLUDING ALL);
CREATE TABLE quien_es_mas_probable (LIKE yo_nunca_nunca INCLUDING ALL);
CREATE TABLE preguntas_incomodas (LIKE yo_nunca_nunca INCLUDING ALL);

CREATE TABLE waiting_messages (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template varchar(500) NOT NULL
);

CREATE TABLE impostor_word (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category varchar(255) NOT NULL,
    word     varchar(255) NOT NULL
);
